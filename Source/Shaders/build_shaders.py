"""Generates the Justiciar Valor effect shaders for both RimWorld versions from one source.

Sources (this folder):
  MJV_FxLib.shaderlib   shared functions
  Effects/*.fx          one effect each: `vec4 MJV_Fx(vec2 uv, vec3 wpos, vec4 col, vec4 p0, vec4 p1)` returning
                        premultiplied RGBA, plus header tags (// @name, // @queue, optional // @texture main)

Outputs:
  1.7/Shaders/<name>.frag.glsl                       GLSL 450 fragment shaders (native Waylith ShaderDefs)
  1.7/Defs/ShaderDefs/MJV_ShaderDefs.xml            the ShaderDefs
  Common/Defs/ShaderTypeDefs/MJV_ShaderTypeDefs.xml ShaderTypeDefs shared by both versions: 1.7 resolves the
                                                    shaderPath's last segment to the ShaderDef of that name, 1.6 looks
                                                    the full path up in the mod's asset bundle
  --unity <project>: Assets/Data/Mortis.JusticiarValor/Materials/JusticiarValor/<name>.shader (Unity ShaderLab) and the
                     bundle builder under Assets/MRK/JusticiarValor/Editor, for 1.6/AssetBundles

All effects blend premultiplied (One, OneMinusSrcAlpha), do not write depth and do not cull.
Usage: python build_shaders.py [--unity <path to the Unity project>] [--check]
"""
import argparse
import os
import re
import shutil
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
MOD_ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
PACKAGE_ID = "Mortis.JusticiarValor"
SHADER_FOLDER = "JusticiarValor"
GENERATED_NOTE = "Generated by Source/Shaders/build_shaders.py from {src}. Do not edit; edit the source and regenerate."

GLSL_PRELUDE = """#define MJV_ATAN2(y, x) atan(y, x)
#define MJV_MOD(x, y) ((x) - (y) * floor((x) / (y)))
"""

GLSL_TEXTURE = """#define MJV_TEX(c) texture(_MainTex, c)
#define MJV_MAINTEX_UV(c) ((c) * u._MainTex_ST.zw + u._MainTex_ST.xy)
"""

HLSL_PRELUDE = """#define vec2 float2
#define vec3 float3
#define vec4 float4
#define mix lerp
#define fract frac
#define MJV_ATAN2(y, x) atan2(y, x)
#define MJV_MOD(x, y) ((x) - (y) * floor((x) / (y)))
"""

HLSL_TEXTURE = """#define MJV_TEX(c) tex2D(_MainTex, c)
#define MJV_MAINTEX_UV(c) ((c) * _MainTex_ST.xy + _MainTex_ST.zw)
"""

# Identifiers that would compile on one target only, or with different meaning.
FORBIDDEN = [
    (r"\bfrac\s*\(", "frac: use fract"),
    (r"\blerp\s*\(", "lerp: use mix"),
    (r"\bsaturate\s*\(", "saturate: use mjv_sat"),
    (r"\bfloat[234]\b", "floatN: use vecN"),
    (r"\batan2?\s*\(", "atan/atan2: use MJV_ATAN2"),
    (r"(?<![A-Za-z_])mod\s*\(", "mod: use MJV_MOD"),
    (r"\bfmod\s*\(", "fmod: use MJV_MOD"),
    (r"\btexture\s*\(|\btex2D\s*\(", "sampling: use MJV_TEX"),
    (r"\bmat[234]\b|\bfloat[234]x[234]\b", "matrices: not portable between the targets"),
    (r"#\s*version", "#version: added by the generator"),
    (r"\bvec[234]\s*\(\s*[^,()]+\)", "single-argument vector constructor: spell out every component"),
    (r"\bpow\s*\((?:[^()]|\([^()]*\))*,\s*2(?:\.0*)?\s*\)", "pow(x, 2.0): use mjv_sq (GLSL pow is undefined for negative bases)"),
    (r"\b(?:bool|int|float|vec[234])\s+(?:line|point|triangle|sample|smooth|flat|precise|centroid|linear|noperspective|packed)\b",
     "a variable named after a keyword of one target (HLSL: line, point, sample...)"),
]


def read(path):
    with open(path, encoding="utf-8") as f:
        return f.read()


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def strip_comments(code):
    code = re.sub(r"/\*.*?\*/", "", code, flags=re.S)
    return re.sub(r"//[^\n]*", "", code)


def check_dialect(name, code):
    problems = []
    body = strip_comments(code)
    # MJV_ATAN2 / MJV_MOD definitions are generated, so the macro names themselves are fine.
    body = body.replace("MJV_ATAN2", "MJV_A2").replace("MJV_MOD", "MJV_MD")
    for pattern, message in FORBIDDEN:
        for m in re.finditer(pattern, body):
            line = body[: m.start()].count("\n") + 1
            problems.append(f"{name}:{line}: {message}: {m.group(0).strip()}")
    return problems


class Effect:
    def __init__(self, path):
        self.path = path
        self.source = read(path)
        tags = dict(re.findall(r"//\s*@(\w+)\s+([^\r\n]*)", self.source))
        self.name = tags["name"].strip()
        self.queue = int(tags.get("queue", "3100"))
        self.textured = tags.get("texture", "").strip() == "main"
        if not self.name.startswith("MJV_"):
            raise SystemExit(f"{path}: effect names need the MJV_ prefix (shader files resolve globally by name)")
        if "MJV_Fx(" not in self.source:
            raise SystemExit(f"{path}: missing vec4 MJV_Fx(...)")
        self.rel = os.path.relpath(path, MOD_ROOT).replace("\\", "/")


def glsl(effect, lib):
    lines = [
        "#version 450",
        "// " + GENERATED_NOTE.format(src=effect.rel),
        "",
        "layout(location = 1) in vec2 vUv;",
        "layout(location = 2) in vec3 vWorldPos;",
        "",
        "layout(location = 0) out vec4 outColor;",
        "",
        "layout(set = 2, binding = 0) uniform MaterialUniforms",
        "{",
        "    vec4 _Color;      // @color @default = vec4(1.0, 1.0, 1.0, 1.0)",
    ]
    if effect.textured:
        lines.append("    vec4 _MainTex_ST; // @default = vec4(0.0, 0.0, 1.0, 1.0)")
    lines += [
        "    vec4 _JVParams;   // @default = vec4(0.0, 0.0, 1.0, 0.0)",
        "    vec4 _JVParams2;  // @default = vec4(0.0, 0.0, 0.0, 0.0)",
        "} u;",
        "",
    ]
    if effect.textured:
        lines += ["layout(set = 2, binding = 1) uniform sampler2D _MainTex;", ""]
    out = "\n".join(lines) + "\n" + GLSL_PRELUDE + (GLSL_TEXTURE if effect.textured else "") + "\n"
    out += lib.strip() + "\n\n" + effect.source.strip() + "\n\n"
    out += "void main()\n{\n    outColor = MJV_Fx(vUv, vWorldPos, u._Color, u._JVParams, u._JVParams2);\n}\n"
    return out


def unity_shader(effect, lib):
    queue_offset = effect.queue - 3000
    queue = "Transparent" if queue_offset == 0 else f"Transparent{queue_offset:+d}"
    props = ['        _Color ("Color", Color) = (1,1,1,1)']
    if effect.textured:
        props.append('        _MainTex ("Texture", 2D) = "white" {}')
    props += ['        _JVParams ("Params", Vector) = (0,0,1,0)', '        _JVParams2 ("Params 2", Vector) = (0,0,0,0)']
    uniforms = ["            float4 _Color;", "            float4 _JVParams;", "            float4 _JVParams2;"]
    if effect.textured:
        uniforms += ["            sampler2D _MainTex;", "            float4 _MainTex_ST;"]
    body = HLSL_PRELUDE + (HLSL_TEXTURE if effect.textured else "") + "\n" + lib.strip() + "\n\n" + effect.source.strip()
    body = "\n".join(("            " + l) if l.strip() else "" for l in body.splitlines())
    return f"""// {GENERATED_NOTE.format(src=effect.rel)}
Shader "{SHADER_FOLDER}/{effect.name}"
{{
    Properties
    {{
{chr(10).join(props)}
    }}
    SubShader
    {{
        Tags {{ "Queue"="{queue}" "IgnoreProjector"="True" "RenderType"="Transparent" "PreviewType"="Plane" }}
        Blend One OneMinusSrcAlpha
        ZWrite Off
        Cull Off
        Pass
        {{
            CGPROGRAM
            #pragma vertex vert
            #pragma fragment frag
            #pragma target 3.0
            #include "UnityCG.cginc"

{chr(10).join(uniforms)}

            struct appdata
            {{
                float4 vertex : POSITION;
                float2 uv : TEXCOORD0;
            }};

            struct v2f
            {{
                float4 pos : SV_POSITION;
                float2 uv : TEXCOORD0;
                float3 wpos : TEXCOORD1;
            }};

            v2f vert(appdata v)
            {{
                v2f o;
                o.pos = UnityObjectToClipPos(v.vertex);
                o.uv = v.uv;
                o.wpos = mul(unity_ObjectToWorld, v.vertex).xyz;
                return o;
            }}

{body}

            float4 frag(v2f i) : SV_Target
            {{
                return MJV_Fx(i.uv, i.wpos, _Color, _JVParams, _JVParams2);
            }}
            ENDCG
        }}
    }}
}}
"""


def shader_defs(effects):
    out = ['<?xml version="1.0" encoding="utf-8"?>', "<!-- " + GENERATED_NOTE.format(src="Source/Shaders/Effects") + " -->",
           "<Defs>"]
    for e in effects:
        out += [
            "  <ShaderDef>",
            f"    <defName>{e.name}</defName>",
            "    <shaderProgram>",
            f"      <fragmentShaderFileName>{e.name}.frag.glsl</fragmentShaderFileName>",
            f"      <useTexture>{'true' if e.textured else 'false'}</useTexture>",
            "      <transparent>true</transparent>",
            "      <blendMode>Custom</blendMode>",
            "      <blendSrcFactor>One</blendSrcFactor>",
            "      <blendDstFactor>OneMinusSrcAlpha</blendDstFactor>",
            "      <cullMode>None</cullMode>",
            "      <depthWrite>false</depthWrite>",
            f"      <renderQueue>{e.queue}</renderQueue>",
        ]
        if e.textured:
            out += ["      <textureWrapOverrides>", "        <li>", "          <key>_MainTex</key>",
                    "          <value>Clamp</value>", "        </li>", "      </textureWrapOverrides>"]
        out += ["    </shaderProgram>", "  </ShaderDef>"]
    out.append("</Defs>")
    return "\n".join(out) + "\n"


def shader_type_defs(effects):
    out = ['<?xml version="1.0" encoding="utf-8"?>', "<!-- " + GENERATED_NOTE.format(src="Source/Shaders/Effects") + "",
           "     1.7 resolves the last path segment to the native ShaderDef of the same name (1.7/Defs/ShaderDefs);",
           f"     1.6 loads Assets/Data/{PACKAGE_ID}/Materials/<shaderPath>.shader from 1.6/AssetBundles. -->", "<Defs>"]
    for e in effects:
        out += ["  <ShaderTypeDef>", f"    <defName>{e.name}</defName>",
                f"    <shaderPath>{SHADER_FOLDER}/{e.name}</shaderPath>", "  </ShaderTypeDef>"]
    out.append("</Defs>")
    return "\n".join(out) + "\n"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--unity", help="Unity project that builds the 1.6 asset bundle")
    parser.add_argument("--check", action="store_true", help="only check the dialect")
    args = parser.parse_args()

    lib_path = os.path.join(HERE, "MJV_FxLib.shaderlib")
    lib = read(lib_path)
    effects_dir = os.path.join(HERE, "Effects")
    effects = [Effect(os.path.join(effects_dir, f)) for f in sorted(os.listdir(effects_dir)) if f.endswith(".fx")]

    problems = check_dialect("MJV_FxLib.shaderlib", lib)
    for e in effects:
        problems += check_dialect(os.path.basename(e.path), e.source)
    names = [e.name for e in effects]
    if len(set(names)) != len(names):
        problems.append("duplicate effect names")
    if problems:
        print("\n".join(problems))
        sys.exit(1)
    if args.check:
        print(f"{len(effects)} effects pass the dialect check")
        return

    glsl_dir = os.path.join(MOD_ROOT, "1.7", "Shaders")
    if os.path.isdir(glsl_dir):
        for f in os.listdir(glsl_dir):
            if f.startswith("MJV_") and f.endswith(".glsl") and f[: -len(".frag.glsl")] not in names:
                os.remove(os.path.join(glsl_dir, f))
    for e in effects:
        write(os.path.join(glsl_dir, e.name + ".frag.glsl"), glsl(e, lib))
    write(os.path.join(MOD_ROOT, "1.7", "Defs", "ShaderDefs", "MJV_ShaderDefs.xml"), shader_defs(effects))
    write(os.path.join(MOD_ROOT, "Common", "Defs", "ShaderTypeDefs", "MJV_ShaderTypeDefs.xml"), shader_type_defs(effects))
    print(f"GLSL and defs for {len(effects)} effects: {', '.join(names)}")

    if args.unity:
        unity = os.path.abspath(args.unity)
        if not os.path.isdir(os.path.join(unity, "Assets")):
            raise SystemExit(f"{unity} is not a Unity project")
        shader_dir = os.path.join(unity, "Assets", "Data", PACKAGE_ID, "Materials", SHADER_FOLDER)
        if os.path.isdir(shader_dir):
            for f in os.listdir(shader_dir):
                if f.endswith(".shader") and f[: -len(".shader")] not in names:
                    os.remove(os.path.join(shader_dir, f))
        for e in effects:
            write(os.path.join(shader_dir, e.name + ".shader"), unity_shader(e, lib))
        editor_dir = os.path.join(unity, "Assets", "MRK", "JusticiarValor", "Editor")
        os.makedirs(editor_dir, exist_ok=True)
        for f in os.listdir(os.path.join(HERE, "Unity")):
            if f.endswith(".cs"):
                shutil.copyfile(os.path.join(HERE, "Unity", f), os.path.join(editor_dir, f))
        print(f"Unity shaders written to {shader_dir}")


if __name__ == "__main__":
    main()
